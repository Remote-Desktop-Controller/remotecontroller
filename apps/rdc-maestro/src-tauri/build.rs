#![allow(clippy::collapsible_if)]

fn main() {
    // Normaliza caminhos com espaços para o formato 8.3 do Windows antes do windres (GNU toolchain)
    if let Ok(out_dir) = std::env::var("OUT_DIR") {
        if out_dir.contains("Remote Desktop Controller") {
            let short_out = out_dir.replace("Remote Desktop Controller", "REMOTE~1");
            unsafe {
                std::env::set_var("OUT_DIR", short_out);
            }
        }
    }

    if let Ok(manifest_dir) = std::env::var("CARGO_MANIFEST_DIR") {
        if manifest_dir.contains("Remote Desktop Controller") {
            let short_manifest = manifest_dir.replace("Remote Desktop Controller", "REMOTE~1");
            unsafe {
                std::env::set_var("CARGO_MANIFEST_DIR", short_manifest);
            }
        }
    }

    // O manifesto de ACL do aplicativo declara os comandos IPC expostos. Isso gera as
    // permissões `allow-<comando>` (permissions/autogenerated) usadas pelas capabilities,
    // incluindo a capability remota que autoriza as WebViews de provedores a devolverem
    // o texto lido ao motor blackboard (Fase 3).
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into());
    let icon_path = std::path::PathBuf::from(&manifest_dir).join("icons/icon.ico");

    // Garante que o diretório `frontendDist` ("../dist") e um index.html existam
    // caso o bundle do frontend ainda não tenha sido compilado (ex: em ambientes de CI).
    let dist_dir = std::path::Path::new(&manifest_dir).join("../dist");
    if !dist_dir.exists() {
        let _ = std::fs::create_dir_all(&dist_dir);
    }
    let fallback_html = dist_dir.join("index.html");
    if !fallback_html.exists() {
        let _ = std::fs::write(
            &fallback_html,
            "<!doctype html><html><head><meta charset=\"UTF-8\"/><title>RDC Maestro</title></head><body><div id=\"root\"></div></body></html>",
        );
    }

    let attrs = tauri_build::Attributes::new()
        .app_manifest(tauri_build::AppManifest::new().commands(&APP_COMMANDS))
        .windows_attributes(tauri_build::WindowsAttributes::new().window_icon_path(&icon_path));

    tauri_build::try_build(attrs).expect("Falha ao executar tauri-build para RDC Maestro");

    // Os alvos de teste (`cargo test`) não recebem o `rustc-link-arg-bins` emitido pelo
    // embed-resource. Sem o recurso compilado o binário de teste fica sem o manifesto
    // Common-Controls v6 e, ao importar `TaskDialogIndirect` (tao/muda), o Windows
    // aborta o processo com STATUS_ENTRYPOINT_NOT_FOUND. O `rustc-link-arg` genérico
    // cobre também os alvos de teste, mantendo a suíte executável na toolchain GNU.
    // Recursos de teste na toolchain GNU.
    //
    // O embed-resource entrega o manifesto Common-Controls v6 (e ícone/versão) apenas aos
    // binários, via `rustc-link-arg-bins`. Sem esse manifesto o Windows aborta qualquer
    // processo que importe `TaskDialogIndirect` (tao/muda) com STATUS_ENTRYPOINT_NOT_FOUND,
    // o que quebra `cargo test`.
    //
    // - `rustc-link-arg-tests` cobre os testes de integração (`tests/`);
    // - o harness unitário da biblioteca é coberto por um `#[link]` restrito a
    //   `cfg(test)` no crate (`src/lib.rs`), que usa esta busca de biblioteca.
    //
    // Assim cada alvo recebe o recurso exatamente uma vez — sem o aviso
    // "'.rsrc merge failure'" que aparecia ao duplicar o arquivo nos binários.
    let is_gnu = std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("gnu");
    if is_gnu {
        if let Ok(out_dir) = std::env::var("OUT_DIR") {
            let resource = std::path::Path::new(&out_dir).join("libresource.a");
            if resource.exists() {
                println!("cargo:rustc-link-search=native={out_dir}");
                println!("cargo:rustc-link-arg-tests={}", resource.display());
            }
        }
    }
}

/// Comandos IPC do Maestro (Fases 1, 3 e 4). Mantenha em sincronia com `invoke_handler`
/// em `src/lib.rs` e com as capabilities em `capabilities/`.
const APP_COMMANDS: [&str; 10] = [
    // Fase 1 - sessões web headless
    "open_provider_login",
    "hide_provider_window",
    "show_provider_window",
    "set_provider_connected",
    "get_all_providers_status",
    // Fase 3 - motor blackboard
    "maestro_receive_reply",
    "maestro_start_mission",
    "maestro_get_last_consensus",
    "maestro_get_mission",
    // Fase 4 - ponte com o daemon local
    "maestro_execute_plan",
];
